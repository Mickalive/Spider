def sha(rel: str) -> str:
    p = os.path.join(HERE, rel)
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def git(*a: str) -> str | None:
    try:
        return subprocess.run(["git", *a], cwd=HERE, capture_output=True, text=True,
                              timeout=30).stdout.strip() or None
    except Exception:  # noqa: BLE001
        return None


def artifact(rel: str, role: str, desc: str, keep: bool = True) -> dict:
    a = {"path": f"research/experiments/{EXP}/{rel}", "role": role, "description": desc}
    try:
        a["sha256"] = sha(rel)
        a["bytes"] = os.path.getsize(os.path.join(HERE, rel))
    except OSError:
        a["sha256"] = None
        a["bytes"] = None
    if not keep:
        a["note"] = "not committed; may be regenerated by re-running the recorded command"
    return a


